const dicts = { ru, en };

export function useT() {
  const lang = useStore((s) => s.settings.lang);
  return (k: TKey) => dicts[lang][k] ?? k;
}

export function useLang() {
  return useStore((s) => s.settings.lang);
}

export const RANKS = {
  ru: ['Новичок', 'Слушатель', 'Ученик', 'Музыкант', 'Знаток', 'Виртуоз', 'Маэстро', 'Абсолютный слух'],
  en: ['Newbie', 'Listener', 'Student', 'Musician', 'Expert', 'Virtuoso', 'Maestro', 'Golden Ear'],
};

export function rankFor(level: number, lang: 'ru' | 'en') {
  const th = [1, 3, 5, 8, 12, 16, 20, 30];
  let i = 0;
  while (i + 1 < th.length && level >= th[i + 1]) i++;
  return RANKS[lang][i];
}
